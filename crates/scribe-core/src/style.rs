pub fn preset_name(preset: Preset, lang: Language) -> &'static str {
    match (preset, lang) {
        (Preset::Default, Language::Fr) => "Par défaut",
        (Preset::Default, Language::En) => "Default",
        (Preset::Clean, Language::Fr) => "Propre",
        (Preset::Clean, Language::En) => "Clean",
        (Preset::Slack, _) => "Slack",
        (Preset::Mail, Language::Fr) => "Mail",
        (Preset::Mail, Language::En) => "Email",
    }
}

pub fn preset_task(preset: Preset, lang: Language) -> &'static str {
    match (preset, lang) {
        (Preset::Default, Language::Fr) => DEFAULT_FR,
        (Preset::Default, Language::En) => DEFAULT_EN,
        (Preset::Clean, Language::Fr) => CLEAN_FR,
        (Preset::Clean, Language::En) => CLEAN_EN,
        (Preset::Slack, Language::Fr) => SLACK_FR,
        (Preset::Slack, Language::En) => SLACK_EN,
        (Preset::Mail, Language::Fr) => MAIL_FR,
        (Preset::Mail, Language::En) => MAIL_EN,
    }
}

fn builtin(id: &str, preset: Preset, keyword: Option<&str>, aliases: &[&str]) -> Style {
    Style {
        id: id.into(),
        preset: Some(preset),
        name: None,
        keyword: keyword.map(String::from),
        aliases: aliases.iter().map(|a| a.to_string()).collect(),
        custom_task: None,
    }
}

/// The built-in styles shipped by this version, default first.
pub fn catalog() -> Vec<Style> {
    vec![
        builtin(DEFAULT_STYLE_ID, Preset::Default, None, &[]),
        builtin("clean", Preset::Clean, Some("clean"), &["propre"]),
        builtin("slack", Preset::Slack, Some("slack"), &[]),
        builtin("mail", Preset::Mail, Some("mail"), &["email", "e-mail", "courriel"]),
    ]
}

pub fn catalog_ids() -> Vec<String> {
    catalog().into_iter().map(|s| s.id).collect()
}

/// The text sent to the LLM and the language it is written in. A style without a task (refused by `validate`)
/// falls back to the default preset.
pub fn task_text(style: &Style, ui: Language) -> (&str, Language) {
    match &style.custom_task {
        Some(c) => (&c.text, c.language),
        None => (preset_task(style.preset.unwrap_or(Preset::Default), ui), ui),
    }
}

pub fn display_name(style: &Style, ui: Language) -> String {
    if let Some(name) = style.name.as_deref().map(str::trim).filter(|n| !n.is_empty()) {
        return name.to_string();
    }
    match (style.preset, &style.keyword) {
        (Some(p), _) => preset_name(p, ui).to_string(),
        (None, Some(k)) => k.clone(),
        (None, None) => style.id.clone(),
    }
}

pub fn find<'s>(styles: &'s [Style], id: &str) -> Option<&'s Style> {
    styles.iter().find(|s| s.id == id)
}

/// Keywords as typed, to send to the transcriber as hints.
pub fn keywords(styles: &[Style]) -> Vec<String> {
    styles
        .iter()
        .filter_map(|s| s.keyword.as_deref().map(str::trim))
        .filter(|k| !k.is_empty())
        .map(String::from)
        .collect()
}

/// Keyword then aliases. A style without keyword (the default) has no trigger.
fn triggers(style: &Style) -> impl Iterator<Item = &str> {
    let aliases: &[String] = if style.keyword.is_some() { &style.aliases } else { &[] };
    style.keyword.as_deref().into_iter().chain(aliases.iter().map(String::as_str))
}

fn check_style(index: usize, s: &Style) -> Result<(), StyleError> {
    if s.aliases.len() > MAX_ALIASES {
        return Err(StyleError::TooManyAliases { index, max: MAX_ALIASES });
    }
    if s.preset.is_none() && s.name.as_deref().is_none_or(|n| n.trim().is_empty()) {
        return Err(StyleError::StyleNameRequired { index });
    }
    if triggers(s).any(|t| folded_tokens(t).is_empty()) {
        return Err(StyleError::TriggerEmpty { index });
    }
    match &s.custom_task {
        None if s.preset.is_none() => Err(StyleError::TaskEmpty { index }),
        Some(c) if c.text.trim().is_empty() => Err(StyleError::TaskEmpty { index }),
        Some(c) if c.text.chars().count() > MAX_TASK_CHARS => {
            Err(StyleError::TaskTooLong { index, max_chars: MAX_TASK_CHARS })
        }
        _ => Ok(()),
    }
}

/// Every rule but "a default style exists", so a list can be grown one style at a time (`repaired`).
fn check_all(styles: &[Style]) -> Result<(), StyleError> {
    if styles.len() > MAX_STYLES {
        return Err(StyleError::TooManyStyles { max: MAX_STYLES });
    }
    let mut seen: Vec<Vec<String>> = Vec::new();
    for (index, s) in styles.iter().enumerate() {
        if (s.id == DEFAULT_STYLE_ID) != s.keyword.is_none() {
            return Err(StyleError::DefaultStyleMissing);
        }
        if styles[..index].iter().any(|o| o.id == s.id) {
            return Err(StyleError::DuplicateStyleId);
        }
        check_style(index, s)?;
        for t in triggers(s) {
            let tokens = folded_tokens(t);
            if seen.contains(&tokens) {
                return Err(StyleError::DuplicateTrigger { trigger: t.to_string() });
            }
            seen.push(tokens);
        }
    }
    Ok(())
}

pub fn validate(styles: &[Style]) -> Result<(), StyleError> {
    check_all(styles)?;
    if find(styles, DEFAULT_STYLE_ID).is_none() {
        return Err(StyleError::DefaultStyleMissing);
    }
    Ok(())
}

/// Puts the first valid default (else the catalog one) first, then keeps each other style, in order, only if adding
/// it keeps the list valid. Returns the dropped styles' errors.
pub fn repaired(mut styles: Vec<Style>) -> (Vec<Style>, Vec<StyleError>) {
    let mut errors = Vec::new();
    let valid_default = |s: &Style| s.id == DEFAULT_STYLE_ID && s.keyword.is_none() && check_style(0, s).is_ok();
    let mut kept: Vec<Style> = match styles.iter().position(valid_default) {
        Some(i) => vec![styles.remove(i)],
        None => {
            errors.push(StyleError::DefaultStyleMissing);
            catalog().into_iter().filter(|s| s.id == DEFAULT_STYLE_ID).collect()
        }
    };
    for s in styles {
        kept.push(s);
        if let Err(e) = check_all(&kept) {
            kept.pop();
            errors.push(e);
        }
    }
    (kept, errors)
}

/// Appends each catalog style of `ids` whose id is free and whose triggers are not taken, within `MAX_STYLES`.
/// Existing styles are never changed. Returns the skipped ids.
pub fn with_builtins(mut styles: Vec<Style>, ids: &[&str]) -> (Vec<Style>, Vec<String>) {
    let mut skipped = Vec::new();
    let catalog = catalog();
    for &id in ids {
        let taken: Vec<Vec<String>> = styles.iter().flat_map(triggers).map(folded_tokens).collect();
        let fits = |b: &Style| {
            styles.len() < MAX_STYLES
                && find(&styles, id).is_none()
                && triggers(b).all(|t| !taken.contains(&folded_tokens(t)))
        };
        match find(&catalog, id).filter(|b| fits(b)) {
            Some(b) => styles.push(b.clone()),
            None => skipped.push(id.to_string()),
        }
    }
    (styles, skipped)
}

// ---------- Detection ----------

const FILLERS_FR: &[&str] =
    &["euh", "heu", "hum", "hmm", "mmm", "bah", "ben", "bon", "alors", "ok", "okay", "mode", "style", "en mode"];
const FILLERS_EN: &[&str] = &["uh", "um", "er", "erm", "hmm", "mmm", "so", "ok", "okay", "well", "mode", "style"];

/// Punctuation allowed right after a trigger (a `-` only when followed by whitespace).
const BOUNDARY_PUNCT: &[char] = &[',', '.', ':', ';', '!', '?', '…', '–', '—'];

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Detection<'s> {
    pub style: &'s Style,
    /// Byte offset of the body in the text.
    pub body_start: usize,
}

struct Token {
    folded: String,
    end: usize,
}

fn fold_into(c: char, out: &mut String) {
    for l in c.to_lowercase() {
        match l {
            'à' | 'â' | 'ä' | 'á' | 'ã' => out.push('a'),
            'ç' => out.push('c'),
            'é' | 'è' | 'ê' | 'ë' => out.push('e'),
            'î' | 'ï' | 'í' => out.push('i'),
            'ô' | 'ö' | 'ó' => out.push('o'),
            'ù' | 'û' | 'ü' | 'ú' => out.push('u'),
            'ÿ' => out.push('y'),
            'œ' => out.push_str("oe"),
            'æ' => out.push_str("ae"),
            'ß' => out.push_str("ss"),
            l => out.push(l),
        }
    }
}

/// Maximal alphanumeric runs, folded (lowercase, no Latin diacritics), with the byte end of each.
fn tokens(text: &str) -> Vec<Token> {
    let mut out: Vec<Token> = Vec::new();
    let mut in_token = false;
    for (i, c) in text.char_indices() {
        if !c.is_alphanumeric() {
            in_token = false;
            continue;
        }
        if !in_token {
            out.push(Token { folded: String::new(), end: i });
            in_token = true;
        }
        let t = out.last_mut().expect("token pushed above");
        fold_into(c, &mut t.folded);
        t.end = i + c.len_utf8();
    }
    out
}

fn folded_tokens(text: &str) -> Vec<String> {
    tokens(text).into_iter().map(|t| t.folded).collect()
}

fn starts_with(tokens: &[Token], phrase: &[String]) -> bool {
    tokens.len() >= phrase.len() && tokens.iter().zip(phrase).all(|(t, p)| t.folded == *p)
}

fn valid_end(text: &str, end: usize) -> bool {
    let mut rest = text[end..].chars();
    match rest.next() {
        None => true,
        Some(c) if c.is_whitespace() || BOUNDARY_PUNCT.contains(&c) => true,
        Some('-') => rest.next().is_some_and(char::is_whitespace),
        _ => false,
    }
}

fn skip_separators(text: &str, from: usize) -> usize {
    let rest = &text[from..];
    let trimmed = rest.trim_start_matches(|c: char| c.is_whitespace() || c == '-' || BOUNDARY_PUNCT.contains(&c));
    from + rest.len() - trimmed.len()
}

/// The style whose trigger opens `text` (after at most `MAX_FILLERS` filler phrases), and where the body starts.
/// The body may be empty: used on a transcript prefix.
pub fn match_prefix<'s>(text: &str, styles: &'s [Style]) -> Option<Detection<'s>> {
    let toks = tokens(text);
    let triggers: Vec<(&Style, Vec<String>)> = styles
        .iter()
        .flat_map(|s| triggers(s).map(move |t| (s, folded_tokens(t))))
        .filter(|(_, t)| !t.is_empty())
        .collect();
    let fillers: Vec<Vec<String>> = FILLERS_FR.iter().chain(FILLERS_EN).map(|f| folded_tokens(f)).collect();
    let mut pos = 0;
    for skipped in 0..=MAX_FILLERS {
        let rest = &toks[pos..];
        let best = triggers
            .iter()
            .filter(|(_, t)| starts_with(rest, t) && valid_end(text, rest[t.len() - 1].end))
            .fold(None::<&(&Style, Vec<String>)>, |best, c| match best {
                Some(b) if b.1.len() >= c.1.len() => Some(b),
                _ => Some(c),
            });
        if let Some((style, t)) = best {
            return Some(Detection { style, body_start: skip_separators(text, rest[t.len() - 1].end) });
        }
        if skipped == MAX_FILLERS {
            break;
        }
        pos += fillers.iter().filter(|f| starts_with(rest, f)).map(Vec::len).max()?;
    }
    None
}

/// `match_prefix` with a non-empty body: a keyword alone is not a keyword.
pub fn detect<'s>(text: &str, styles: &'s [Style]) -> Option<Detection<'s>> {
    match_prefix(text, styles).filter(|d| !body(text, d).is_empty())
}

pub fn body<'t>(text: &'t str, d: &Detection) -> &'t str {
    text[d.body_start..].trim_end()
}

