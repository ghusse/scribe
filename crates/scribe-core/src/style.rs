    #[test]
    fn with_builtins_adds_missing_ones_and_skips_taken_ids_or_triggers() {
        let mut existing = with_default(vec![user("u", "courriel", &[])]);
        existing[0].custom_task = Some(CustomTask { text: "mine".into(), language: Language::En });
        let (styles, skipped) = with_builtins(existing.clone(), &["default", "clean", "slack", "mail", "nope"]);
        assert_eq!(&styles[..2], &existing[..], "existing styles unchanged");
        assert_eq!(styles[2..].iter().map(|s| s.id.as_str()).collect::<Vec<_>>(), ["clean", "slack"]);
        assert_eq!(skipped, ["default", "mail", "nope"]);
        assert_eq!(validate(&styles), Ok(()));

        let (again, skipped) = with_builtins(styles.clone(), &["clean"]);
        assert_eq!((again, skipped), (styles, vec!["clean".to_string()]));
    }

