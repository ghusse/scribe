//! Dictation styles: a named task for the corrector, chosen by a spoken keyword at the start of the dictation.
use serde::{Deserialize, Serialize};

use crate::lang::Language;

pub const DEFAULT_STYLE_ID: &str = "default";
pub const MAX_STYLES: usize = 10;
pub const MAX_ALIASES: usize = 8;
pub const MAX_TASK_CHARS: usize = 4000;
/// Filler phrases skipped before the keyword.
pub const MAX_FILLERS: usize = 3;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Preset {
    Default,
    Clean,
    Slack,
    Mail,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CustomTask {
    pub text: String,
    /// UI language when the text was written; the text keeps it when the UI language changes.
    pub language: Language,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Style {
    /// Stable id: "default", "clean", "slack", "mail", or a UUID generated by the UI for user styles.
    pub id: String,
    /// Built-in origin: name fallback, task fallback and "reset" target. None for user styles.
    pub preset: Option<Preset>,
    /// None: the preset's localized name.
    pub name: Option<String>,
    /// None only for the default style. Also sent to the transcriber as a hint.
    pub keyword: Option<String>,
    /// Extra spoken forms. Not sent as hints, because aliases are often mishearings.
    pub aliases: Vec<String>,
    /// None: the preset text in the current UI language.
    pub custom_task: Option<CustomTask>,
}

/// Why `validate` refuses a style list. Styles are named by their index in the list.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, thiserror::Error)]
#[serde(tag = "code", rename_all = "snake_case")]
pub enum StyleError {
    #[error("exactly one default style without keyword is required, and every other style needs a keyword")]
    DefaultStyleMissing,
    #[error("duplicate style id")]
    DuplicateStyleId,
    #[error("more than {max} styles")]
    TooManyStyles { max: usize },
    #[error("style {index}: more than {max} aliases")]
    TooManyAliases { index: usize, max: usize },
    #[error("style {index}: name required")]
    StyleNameRequired { index: usize },
    #[error("style {index}: empty keyword or alias")]
    TriggerEmpty { index: usize },
    #[error("trigger used twice: {trigger}")]
    DuplicateTrigger { trigger: String },
    #[error("style {index}: empty task")]
    TaskEmpty { index: usize },
    #[error("style {index}: task longer than {max_chars} characters")]
    TaskTooLong { index: usize, max_chars: usize },
}

