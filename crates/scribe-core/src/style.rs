    fn with_default(mut rest: Vec<Style>) -> Vec<Style> {
        rest.insert(0, catalog().remove(0));
        rest
    }

    #[test]
    fn validate_reports_each_error_with_its_index() {
        let ok = with_default(vec![user("a", "alpha", &[])]);
        assert_eq!(validate(&ok), Ok(()));

        let cases: Vec<(Vec<Style>, StyleError)> = vec![
            (vec![user("a", "alpha", &[])], StyleError::DefaultStyleMissing),
            (with_default(vec![catalog().remove(0)]), StyleError::DuplicateStyleId),
            (with_default(vec![Style { keyword: None, ..user("a", "alpha", &[]) }]), StyleError::DefaultStyleMissing),
            (with_default(vec![user("a", "alpha", &[]), user("a", "beta", &[])]), StyleError::DuplicateStyleId),
            (
                with_default((0..MAX_STYLES).map(|i| user(&format!("s{i}"), &format!("k{i}"), &[])).collect()),
                StyleError::TooManyStyles { max: MAX_STYLES },
            ),
            (
                with_default(vec![user("a", "alpha", &["1", "2", "3", "4", "5", "6", "7", "8", "9"])]),
                StyleError::TooManyAliases { index: 1, max: MAX_ALIASES },
            ),
            (
                with_default(vec![Style { name: Some(" ".into()), ..user("a", "alpha", &[]) }]),
                StyleError::StyleNameRequired { index: 1 },
            ),
            (with_default(vec![user("a", "-", &[])]), StyleError::TriggerEmpty { index: 1 }),
            (with_default(vec![user("a", "alpha", &["…"])]), StyleError::TriggerEmpty { index: 1 }),
            (
                with_default(vec![user("a", "alpha", &[]), user("b", "beta", &["Alpha!"])]),
                StyleError::DuplicateTrigger { trigger: "Alpha!".into() },
            ),
            (
                with_default(vec![user("a", "compte-rendu", &["Compte rendu"])]),
                StyleError::DuplicateTrigger { trigger: "Compte rendu".into() },
            ),
            (
                with_default(vec![Style { custom_task: None, ..user("a", "alpha", &[]) }]),
                StyleError::TaskEmpty { index: 1 },
            ),
            (
                with_default(vec![Style {
                    custom_task: Some(CustomTask { text: " \n".into(), language: Language::En }),
                    ..catalog().remove(2)
                }]),
                StyleError::TaskEmpty { index: 1 },
            ),
            (
                with_default(vec![Style {
                    custom_task: Some(CustomTask { text: "é".repeat(MAX_TASK_CHARS + 1), language: Language::En }),
                    ..user("a", "alpha", &[])
                }]),
                StyleError::TaskTooLong { index: 1, max_chars: MAX_TASK_CHARS },
            ),
        ];
        for (styles, expected) in cases {
            assert_eq!(validate(&styles), Err(expected.clone()), "{expected:?}");
        }
        let at_limit = Style {
            custom_task: Some(CustomTask { text: "é".repeat(MAX_TASK_CHARS), language: Language::En }),
            aliases: (0..MAX_ALIASES).map(|i| format!("alias{i}")).collect(),
            ..user("a", "alpha", &[])
        };
        assert_eq!(validate(&with_default(vec![at_limit])), Ok(()));
        assert_eq!(validate(&[]), Err(StyleError::DefaultStyleMissing));
    }

